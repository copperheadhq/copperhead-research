"""LaTeX macros and tables from build/results/results.json, so the report
types no result by hand.

Run: python scripts/tex_numbers.py -> report/generated/{numbers,tables}.tex
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import geometry  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
R = json.loads((ROOT / "build" / "results" / "results.json").read_text())
V = R["variants"]
SUFFIX = {"A": "A", "B": "B", "C": "C", "C_far": "Cfar", "D": "D", "E": "E", "F": "F", "C_cal": "Ccal",
          "D_cal": "Dcal", "F_cal": "Fcal", "S_ref": "Sref", "S_loose": "Sloose", "S_tight": "Stight",
          "B_R075": "BRsmall", "B_R3": "BRlarge", "B_sl": "Bsl", "C_sl": "Csl", "D_sl": "Dsl", "F_sl": "Fsl",
          "S_ref_sl": "Srefsl", "S_loose_sl": "Sloosesl", "S_tight_sl": "Stightsl"}
LABEL = {"A": "A straight", "B": "B untuned", "C": "C sparse", "C_far": "C far", "D": "D dense",
         "E": "E pair exc.", "F": "F trombone", "C_cal": "C, EM-sized", "D_cal": "D, EM-sized",
         "F_cal": "F, EM-sized", "S_ref": "Serp. ref.", "S_loose": "Serp. 1.0 mm", "S_tight": "Serp. 0.15 mm",
         "B_R075": "B, R 0.75", "B_R3": "B, R 3.0", "B_sl": "B stripline", "C_sl": "C stripline",
         "D_sl": "D stripline", "F_sl": "F stripline", "S_ref_sl": "Serp. ref. SL", "S_loose_sl": "Serp. 1.0 mm SL",
         "S_tight_sl": "Serp. 0.15 mm SL"}


def sci(x):
    """A small number as LaTeX: 3.3e-07 -> 3.3\\times10^{-7}, in math mode."""
    mant, exp = f"{x:.1e}".split("e")
    return f"${mant}\\times10^{{{int(exp)}}}$"


def f(x, n=2):
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{n}f}"


def main():
    p = geometry.params()
    out = ["% generated by scripts/tex_numbers.py from build/results/results.json; do not edit"]
    m = lambda name, val: out.append(f"\\newcommand{{\\{name}}}{{{val}}}")  # noqa: E731
    a = R["analytic"]
    m("BendDL", f(a["bend_mismatch_mm"], 3))
    m("BendDLmil", f(a["bend_mismatch_mil"], 1))
    m("SkewEpsThreeEight", f(a["skew_ps_at_eps_3.8"], 1))
    m("EpsNineFive", f(a["eps_for_9.5ps"], 2))
    m("EpsSingle", f(a["single_line"]["eps_eff"], 3))
    m("ZSingle", f(a["single_line"]["z0_ohm"], 1))
    m("SkewSingle", f(a["single_line"]["skew_ps"], 2))
    m("PsPerMm", f(R["ps_per_mm_single"], 3))
    c = R["mtl_calibration"]
    m("EpsOdd", f(c["eps_odd"], 2))
    m("EpsEven", f(c["eps_even"], 2))
    m("ZOdd", f(c["z_odd"], 1))
    m("ZEven", f(c["z_even"], 1))
    m("ZDiff", f(2 * c["z_odd"], 1))
    m("ZComm", f(c["z_even"] / 2, 1))
    m("SkewOdd", f(a["bend_mismatch_mm"] * math.sqrt(c["eps_odd"]) / 299792458.0 * 1e9, 2))
    m("SkewEven", f(a["bend_mismatch_mm"] * math.sqrt(c["eps_even"]) / 299792458.0 * 1e9, 2))
    m("BendEta", f(R["bend_eta"], 3))
    u = R["uncertainty_ps"]
    m("UncUntuned", f(u.get("untuned"), 2))
    m("UncTunedC", f(u.get("tuned_C"), 2))
    m("UncTunedD", f(u.get("tuned_D"), 2))
    if u.get("serpentine") is not None:
        m("UncSerp", f(u["serpentine"], 2))
    for v, row in V.items():
        s = SUFFIX[v]
        t50 = row["timing"]["50"]
        m(f"Skew{s}", f(t50["skew"], 2))
        if row.get("uncertainty_ps") is not None:
            m(f"Unc{s}", f(row["uncertainty_ps"], 2))
        m(f"SkewAbs{s}", f(abs(t50["skew"]), 2))
        m(f"Delay{s}", f(t50["t50_d"], 1))
        m(f"Vc{s}", f(t50["vc_pp_rel"] * 100, 2))
        for r in row["timing"]:
            m(f"Skew{s}R{''.join('abcdefghij'[int(ch)] for ch in r)}", f(row["timing"][r]["skew"], 2))
        if "eta" in t50:
            m(f"Eta{s}", f(t50["eta"], 2))
            m(f"EtaPct{s}", f(t50["eta"] * 100, 0))
        if "added_mm" in row:
            m(f"Added{s}", f(row["added_mm"], 3))
        if "mtl_skew_50" in row:
            m(f"Mtl{s}", f(row["mtl_skew_50"], 2))
        bd = row["bands"]["0.1-20GHz"]
        m(f"SddMax{s}", f(bd["Sdd11_max_dB"], 1))
        m(f"ScdMax{s}", f(bd["Scd21_max_dB"], 1))
        m(f"ScdRms{s}", f(bd["Scd21_mean_dB"], 1))
        m(f"SddMin{s}", f(bd["Sdd21_min_dB"], 2))
        m(f"Zmax{s}", f(row["tdr_35ps"]["zdiff_max"], 1))
        m(f"EyeH{s}", f(row["eye"]["16"]["eye_height_rel"] * 100, 1))
        m(f"EyeW{s}", f(row["eye"]["16"]["eye_width_ui"], 3))
        m(f"EyeVc{s}", f(row["eye"]["16"]["vc_pp_rel"] * 100, 1))
        m(f"EyeHTen{s}", f(row["eye"]["10"]["eye_height_rel"] * 100, 1))
        m(f"EyeVcTen{s}", f(row["eye"]["10"]["vc_pp_rel"] * 100, 1))
        m(f"Area{s}", f(row["area_mm2"], 2))
        m(f"Recip{s}", sci(row["checks"]["reciprocity_max_abs_diff"]))
        m(f"Pass{s}", f(row["checks"]["passivity_max_singular_value"], 3))
        m(f"Trunc{s}", f(max(row["checks"]["truncation_dB"].values()), 0))
        for k, val in row["skew_fd_ps"].items():
            m(f"Fd{s}G{''.join('abcdefghij'[int(ch)] for ch in k)}", f(val, 2))
        if "amplitude" in row["tuning"]:
            m(f"Amp{s}", f(row["tuning"]["amplitude"], 3))
        if "amplitude_nominal" in row["tuning"]:
            m(f"AmpRule{s}", f(row["tuning"]["amplitude_nominal"], 3))
    # derived quantities the text quotes
    sb = V["B"]["timing"]["50"]["skew"]
    m("BendErrPct", f(abs(a["single_line"]["skew_ps"] - sb) / a["single_line"]["skew_ps"] * 100, 1))
    m("DelayAddE", f(V["E"]["timing"]["50"]["t50_d"] - V["B"]["timing"]["50"]["t50_d"], 1))
    for v in ("C", "C_far", "D", "F", "C_cal", "D_cal", "F_cal"):
        if v in V:
            m(f"RemovedPct{SUFFIX[v]}", f((1 - V[v]["timing"]["50"]["skew"] / sb) * 100, 0))
    # the tuning's shortfall per excursion: what the line model says the tuning
    # removed, less what full wave says it removed, so the line model's own
    # error on the bare bend (skew_B - mtl_B) is not charged to the excursions
    bend_err = sb - V["B"]["mtl_skew_50"]
    m("MtlBendErr", f(bend_err, 2))
    per = {v: (V[v]["timing"]["50"]["skew"] - V[v]["mtl_skew_50"] - bend_err) / V[v]["tuning"]["excursions"]
           for v in ("C", "D", "F") if v in V}
    for v, val in per.items():
        m(f"PerExc{SUFFIX[v]}", f(val, 1))
    m("PerExcMin", f(min(per.values()), 1))
    m("PerExcMax", f(max(per.values()), 1))
    # fold penalties in points, from the efficiencies as the tables print them
    # (two decimals), so the text and the tables agree
    r2 = lambda x: round(x, 2)  # noqa: E731
    if "S_loose_sl" in V and "S_tight_sl" in V:
        m("FoldPenaltySl", f((r2(V["S_loose_sl"]["timing"]["50"]["eta"]) - r2(V["S_tight_sl"]["timing"]["50"]["eta"])) * 100, 0))
    if "bend_eta_sl" in R:
        m("BendEtaSl", f(R["bend_eta_sl"], 3))
        m("SkewGeoSl", f(R["skew_geometric_sl"], 2))
        m("BendErrPctSl", f(abs(R["skew_geometric_sl"] - V["B_sl"]["timing"]["50"]["skew"]) / R["skew_geometric_sl"] * 100, 1))
        m("PsPerMmSl", f(R["ps_per_mm_stripline"], 3))
    if "B_sl" in V:
        sbs = V["B_sl"]["timing"]["50"]["skew"]
        for v in ("C_sl", "D_sl", "F_sl"):
            if v in V:
                m(f"RemovedPct{SUFFIX[v]}", f((1 - V[v]["timing"]["50"]["skew"] / sbs) * 100, 0))
    if "S_loose" in V and "S_tight" in V:
        m("FoldPenalty", f((r2(V["S_loose"]["timing"]["50"]["eta"]) - r2(V["S_tight"]["timing"]["50"]["eta"])) * 100, 0))
    m("ShortfallD", f(a["tuning"]["D"]["shortfall_if_2NA_used_mm"], 2))
    m("ChamferCellsMedium", f(p["tuning"]["chamfer"] / p["simulation"]["levels"]["medium"], 1))
    m("FoldD", f(V["D"]["tuning"]["fold_edge_spacing"], 2))
    m("RecipMax", sci(max(r["checks"]["reciprocity_max_abs_diff"] for r in V.values())))
    m("PassMax", f(max(r["checks"]["passivity_max_singular_value"] for r in V.values()), 3))
    m("TruncWorst", f(-max(max(r["checks"]["truncation_dB"].values()) for r in V.values()), 0))
    # what each millimetre the EM-informed sizing added actually delivered
    for v in ("C", "D", "F"):
        cv = v + "_cal"
        if cv in V:
            extra = V[cv]["P_len"] - V[v]["P_len"]
            gain = V[v]["timing"]["50"]["skew"] - V[cv]["timing"]["50"]["skew"]
            m(f"Marg{v}", f(gain / (extra * R["ps_per_mm_single"]), 2))
            m(f"MargPct{v}", f(gain / (extra * R["ps_per_mm_single"]) * 100, 0))
            m(f"Extra{v}", f(extra, 3))
    cal = [abs(V[v]["timing"]["50"]["skew"]) for v in ("C_cal", "D_cal", "F_cal") if v in V]
    if cal:
        m("CalMin", f(min(cal), 2))
        m("CalMax", f(max(cal), 2))
    for v, cv in R["convergence"].items():
        s = SUFFIX[v]
        for l, val in cv["skew_50"].items():
            m(f"Conv{s}{l.capitalize()}", f(val, 2))
        m(f"Gci{s}", f(cv["gci"], 2))
        m(f"BoundMed{s}", f(cv["bound_medium"], 2))
        if cv.get("extrapolated") is not None:
            m(f"Ext{s}", f(cv["extrapolated"], 2))
        m(f"ConvMono{s}", "monotonic" if cv["monotonic"] else "oscillatory")
        if cv.get("order") is not None:
            m(f"Order{s}", f(cv["order"], 1))
    pr = R["pareto"]
    short = {"B": "B", "C": "C", "C_far": "C far", "D": "D", "E": "E", "F": "F", "C_cal": "C (EM-sized)",
             "D_cal": "D (EM-sized)", "F_cal": "F (EM-sized)"}
    m("ParetoAll", ", ".join(short[v] for v in pr["front_all"]))
    m("GeomCount", str(len(V)))
    m("GeomCountMs", str(len([v for v in V if not v.endswith("_sl")])))
    m("GeomCountSl", str(len([v for v in V if v.endswith("_sl")])))
    # experiments actually run
    runs = list((ROOT / "runs").glob("*/*/p*/provenance.json"))
    recs = [json.loads(r.read_text()) for r in runs]
    recs = [r for r in recs if r.get("returncode") == 0]
    m("RunCount", str(len(recs)))
    m("RunHours", f(sum(r["wall_seconds"] for r in recs) / 3600, 1))
    m("SolverVersion", recs[0]["solver_version"].replace("_", "\\_"))
    m("CellsMedium", f(max(r["cells"] for r in recs if r["level"] == "medium" and r["variant"] == "B") / 1e6, 2))
    m("CellsFine", f(max(r["cells"] for r in recs if r["level"] == "fine" and r["variant"] == "B") / 1e6, 2))
    # the serpentines' tuning sections: same corners, amplitude and added length, but not
    # the same section length, so P runs uncoupled from N over a different length
    for v, s in (("S_loose", "Sloose"), ("S_tight", "Stight")):
        tu = geometry.build(v, p)["tuning"]
        m(f"SecLen{s}", f(tu["section_end"] - tu["section_start"], 2))
    gen = ROOT / "report" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "numbers.tex").write_text("\n".join(out) + "\n")

    # ---------------------------------------------------------------- tables
    t = []
    order = [v for v in ("A", "B", "E", "C", "C_far", "D", "F", "C_cal", "D_cal", "F_cal") if v in V]
    t.append("% metric table")
    t.append("\\begin{tabular}{@{}lrrrrrrrrr@{}}\\toprule")
    t.append("Variant & $\\Delta L_\\mathrm{add}$ & Skew & $\\eta$ & MTL & $V_c$ p-p & $|S_{dd11}|$ & $|S_{cd21}|$ & "
             "$Z_\\mathrm{diff}$ & Area \\\\")
    t.append(" & (mm) & (ps) & & (ps) & (\\%) & max (dB) & RMS (dB) & max ($\\Omega$) & (mm$^2$) \\\\\\midrule")
    for v in order:
        row = V[v]
        t50 = row["timing"]["50"]
        bd = row["bands"]["0.1-20GHz"]
        unc = row.get("uncertainty_ps")
        own = row.get("uncertainty_from") in (None, v)
        sk = f(t50["skew"], 2) + (f" $\\pm$ {f(unc, 2)}" + ("" if own else "$^\\dagger$") if unc else "")
        t.append(f"{LABEL[v]} & {f(row.get('added_mm'), 3) if 'added_mm' in row else '--'} & {sk} & "
                 f"{f(t50.get('eta'), 2)} & {f(row.get('mtl_skew_50'), 2)} & {f(t50['vc_pp_rel'] * 100, 2)} & "
                 f"{f(bd['Sdd11_max_dB'], 1)} & {f(bd['Scd21_mean_dB'], 1) if v != 'A' else '--'} & "
                 f"{f(row['tdr_35ps']['zdiff_max'], 1)} & {f(row['area_mm2'], 2)} \\\\")
    t.append("\\bottomrule\\end{tabular}")
    (gen / "table_metrics.tex").write_text("\n".join(t) + "\n")

    t = ["\\begin{tabular}{@{}lrrr@{}}\\toprule", "Variant & Reciprocity & Passivity & Truncation \\\\",
         " & $\\max|S_{ij}-S_{ji}|$ & $\\max\\sigma(S)$ & (dB) \\\\\\midrule"]
    for v in V:
        ck = V[v]["checks"]
        t.append(f"{LABEL[v]} & {sci(ck['reciprocity_max_abs_diff'])} & {ck['passivity_max_singular_value']:.3f} & "
                 f"{max(ck['truncation_dB'].values()):.0f} \\\\")
    t.append("\\bottomrule\\end{tabular}")
    (gen / "table_checks.tex").write_text("\n".join(t) + "\n")

    cells = p["simulation"]["levels"]
    order_l = sorted(cells, key=lambda l: -cells[l])
    t = ["\\begin{tabular}{@{}l" + "r" * len(order_l) + "rrl@{}}\\toprule",
         "Variant & " + " & ".join(f"{cells[l] * 1000:g}\\,\\textmu m" for l in order_l)
         + " & GCI & 40\\,\\textmu m & Convergence \\\\",
         " & " + " & ".join("(ps)" for _ in order_l) + " & finest & bound & \\\\\\midrule"]
    for v, cv in R["convergence"].items():
        s5 = cv["skew_50"]
        cellsv = " & ".join(f(s5[l], 2) if l in s5 else "--" for l in order_l)
        t.append(f"{LABEL[v]} & {cellsv} & $\\pm${f(cv['gci'], 2)} & $\\pm${f(cv['bound_medium'], 2)} & "
                 f"{'monotonic' if cv['monotonic'] else 'oscillatory'} \\\\")
    t.append("\\bottomrule\\end{tabular}")
    (gen / "table_convergence.tex").write_text("\n".join(t) + "\n")

    t = ["\\begin{tabular}{@{}l" + "r" * len(order_l) + "@{}}\\toprule",
         "$\\eta$ on each mesh & " + " & ".join(f"{cells[l] * 1000:g}\\,\\textmu m" for l in order_l) + " \\\\\\midrule"]
    for v, row in R.get("eta_by_level", {}).items():
        t.append(f"{LABEL[v]} & " + " & ".join(f(row[l], 2) if l in row else "--" for l in order_l) + " \\\\")
    t.append("\\bottomrule\\end{tabular}")
    (gen / "table_eta_levels.tex").write_text("\n".join(t) + "\n")
    for v, row in R.get("eta_by_level", {}).items():
        vals = list(row.values())
        m(f"EtaMin{SUFFIX[v]}", f(min(vals), 2))
        m(f"EtaMax{SUFFIX[v]}", f(max(vals), 2))
    if all(v in R.get("eta_by_level", {}) for v in ("S_loose", "S_tight")):
        el = R["eta_by_level"]
        pen = [round(el["S_loose"][l], 2) - round(el["S_tight"][l], 2) for l in el["S_loose"] if l in el["S_tight"]]
        m("FoldPenMin", f(min(pen) * 100, 0))
        m("FoldPenMax", f(max(pen) * 100, 0))
    (gen / "numbers.tex").write_text("\n".join(out) + "\n")

    st, pr_, fx, sim = p["stackup"], p["pair"], p["fixture"], p["simulation"]
    rows = [("Dielectric height $h$", "mm", st["dielectric_height"], "fixed"),
            ("Relative permittivity $\\varepsilon_r$", "--", st["epsilon_r"], "fixed"),
            ("Loss tangent at 5 GHz", "--", st["loss_tangent"], "fixed, $\\propto 1/f$"),
            ("Copper thickness / $\\sigma$", "mm / MS/m", f"{st['copper_thickness']} / {st['copper_conductivity'] / 1e6:g}", "sheet model"),
            ("Trace width $w$", "mm", pr_["width"], "fixed"),
            ("Pair pitch $s$ (centre to centre)", "mm", pr_["pitch"], "fixed, 20 mil"),
            ("Bend radius of P, $R$", "mm", fx["bend_radius"], "0.75, 1.5, 3.0"),
            ("Leg length (launch to bend)", "mm", fx["leg_length"], "fixed"),
            ("Excursions $N$", "--", "1, 2, 4", "F, C, D"),
            ("Amplitude $A$", "mm", "solved", "0.29--1.08"),
            ("Excursion top / gap", "mm", "0.45--3.0", "per family"),
            ("Corner chamfer", "mm", p["tuning"]["chamfer"], "fixed"),
            ("Stripline plane spacing", "mm", p["stripline"]["plane_spacing"], "trace midway"),
            ("Distance to bend $D$", "mm", p["tuning"]["gap_to_bend"], "0.5 or at launch"),
            ("Serpentine added length", "mm", p["serpentine"]["added_length"], "fold gap 1.0, 0.15"),
            ("Edge (10--90\\,\\%)", "ps", "35--300", "post-processing"),
            ("Bandwidth", "GHz", "0--30", "Gaussian pulse"),
            ("Finest cell (coarse/medium/fine)", "\\textmu m",
             f"{sim['levels']['coarse'] * 1000:g}/{sim['levels']['medium'] * 1000:g}/{sim['levels']['fine'] * 1000:g}", "convergence")]
    t = ["\\begin{tabular}{@{}llll@{}}\\toprule", "Parameter & Unit & Value & Range or note \\\\\\midrule"]
    for name, unit, val, note in rows:
        t.append(f"{name} & {unit} & {val} & {note} \\\\")
    t.append("\\bottomrule\\end{tabular}")
    (gen / "table_parameters.tex").write_text("\n".join(t) + "\n")
    print("wrote", gen)


if __name__ == "__main__":
    main()
